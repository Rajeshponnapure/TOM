"""Godot 4 games: write a real project, run it headless in Godot to prove it works, open it.

Same games, colours and layout as the pygame versions (so TOM's autopilot can play them too), written in
GDScript on a shared runtime (templates/godot/tom_base.gd). Verification runs the actual engine:
`godot --headless --path <game> -- --selftest=600` must print its TOM_SELFTEST line with no script error.
"""
from __future__ import annotations

import glob
import json
import os
import re
import shutil
import subprocess
from typing import Any, Dict, Optional

from tom_core.games import studio, themes

TEMPLATES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "templates", "godot")
GENRES = ("snake", "runner", "flappy")


def find_godot(console: bool = True) -> str:
    """The Godot 4 executable ('' if not installed). The console build prints to stdout (for checks)."""
    names = ("godot_console", "godot") if console else ("godot", "godot_console")
    for name in names:
        found = shutil.which(name)
        if found:
            return found
    local = os.environ.get("LOCALAPPDATA", "")
    patterns = [os.path.join(local, "Microsoft", "WinGet", "Packages", "GodotEngine*", "Godot_v4*_win64*.exe"),
                os.path.join(os.environ.get("ProgramFiles", r"C:\Program Files"), "Godot*", "Godot_v4*.exe")]
    for pattern in patterns:
        hits = sorted(glob.glob(pattern))
        if hits:
            wanted = [h for h in hits if h.endswith("_console.exe") == console]
            return (wanted or hits)[-1]
    return ""


def _project_file(title: str, width: int, height: int) -> str:
    return (
        "; Engine configuration file. Generated by TOM.\n\nconfig_version=5\n\n[application]\n\n"
        f"config/name={json.dumps(title)}\nrun/main_scene=\"res://main.tscn\"\n"
        "config/features=PackedStringArray(\"4.7\")\n\n[display]\n\n"
        f"window/size/viewport_width={width}\nwindow/size/viewport_height={height}\n"
        "window/size/resizable=false\n\n[rendering]\n\nrenderer/rendering_method=\"gl_compatibility\"\n"
        "renderer/rendering_method.mobile=\"gl_compatibility\"\n")


_SCENE = ('[gd_scene load_steps=2 format=3]\n\n[ext_resource type="Script" path="res://main.gd" id="1"]\n\n'
          '[node name="Main" type="Node2D"]\nscript = ExtResource("1")\n')


def self_test(path: str, frames: int = 600, timeout: int = 120) -> Dict[str, Any]:
    exe = find_godot(console=True)
    if not exe:
        return {"ok": False, "error": "Godot isn't installed (winget install GodotEngine.GodotEngine)."}
    argv = [exe, "--headless", "--path", path, "--quit-after", str(frames + 600), "--", f"--selftest={frames}"]
    try:
        proc = subprocess.run(argv, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return {"ok": False, "error": f"Godot did not finish the self-test in {timeout}s"}
    out = (proc.stdout or "") + "\n" + (proc.stderr or "")
    errors = [ln.strip() for ln in out.splitlines() if re.search(r"SCRIPT ERROR|Parse Error|ERROR:", ln)]
    line = next((ln for ln in (proc.stdout or "").splitlines() if ln.startswith("TOM_SELFTEST ")), "")
    if errors or not line:
        return {"ok": False, "returncode": proc.returncode,
                "error": "\n".join(errors[:8]) or out.strip()[-800:] or "no output from Godot"}
    stats = json.loads(line[len("TOM_SELFTEST "):])
    ok = int(stats.get("frames", 0)) >= frames
    return {"ok": ok, "stats": stats, "error": "" if ok else f"stopped after {stats.get('frames')} frames",
            "engine_version": _version(exe)}


def _version(exe: str) -> str:
    try:
        return subprocess.run([exe, "--version"], capture_output=True, text=True, timeout=30).stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        return ""


def create(request: str, output_dir: Optional[str] = None, frames: int = 600) -> Dict[str, Any]:
    spec = studio.plan(request)
    genre = spec["genre"]
    if genre not in GENRES:
        return {"status": "needs_input", "engine": "godot", "message": (
            f"In Godot I can build and verify: {', '.join(GENRES)}. "
            f"{'A ' + genre + ' game' if genre else 'That game'} I can make in Python (pygame) instead — "
            "say \"make it in pygame\", or pick one of those for Godot.")}
    if not find_godot():
        return {"status": "error", "engine": "godot",
                "message": "Godot isn't installed. Install it with: winget install GodotEngine.GodotEngine"}
    if output_dir is None:
        from tools.project_paths import workspace_path
        output_dir = str(workspace_path("games"))
    os.makedirs(output_dir, exist_ok=True)
    path = studio._unique_dir(output_dir, studio.slug(spec["title"]) + "_godot")
    os.makedirs(path)
    shutil.copyfile(os.path.join(TEMPLATES, "tom_base.gd"), os.path.join(path, "tom_base.gd"))
    shutil.copyfile(os.path.join(TEMPLATES, f"{genre}.gd"), os.path.join(path, "main.gd"))
    settings = studio.game_settings(genre, spec["difficulty"])
    cfg = {"title": spec["title"], "width": 800, "height": 600, "fps": 60, "theme": spec["theme"],
           "difficulty": spec["difficulty"], "colors": themes.colors(spec["theme"]), "game": settings}
    info = studio.GENRES[genre]
    files = {
        "project.godot": _project_file(spec["title"], 800, 600),
        "main.tscn": _SCENE,
        "config.json": json.dumps(cfg, indent=2),
        "tom_game.json": json.dumps({"engine": "godot", "genre": genre, "title": spec["title"],
                                     "window_title": spec["title"], "width": 800, "height": 600,
                                     "colors": cfg["colors"], "game": settings, "controls": info.controls,
                                     "entry": "main.tscn", "made_by": "TOM"}, indent=2),
        "README.md": (f"# {spec['title']}\n\n{info.blurb}\n\nA Godot 4 game made by TOM.\n\n"
                      "Open the folder in Godot (Import → project.godot) and press F5, or run `run.bat`.\n"),
        "run.bat": "@echo off\ncd /d \"%~dp0\"\ngodot --path .\n",
    }
    for name, content in files.items():
        with open(os.path.join(path, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
    test = self_test(path, frames)
    result = {"engine": "godot", "path": path, "title": spec["title"], "genre": genre, "theme": spec["theme"],
              "controls": info.controls, "verified": test["ok"], "self_test": test}
    if test["ok"]:
        s = test["stats"]
        result.update(status="success", message=(
            f"Made the Godot game \"{spec['title']}\" — {info.blurb} Godot {test.get('engine_version', '')} ran it "
            f"headless for {s['frames']} frames ({s['rounds']} round(s) by a random bot) with no script errors. "
            f"Open {path} in Godot, or ask me to start it."))
    else:
        result.update(status="error", message=f"The Godot project in {path} failed its run in Godot: {test['error'][-600:]}")
    return result


def launch(path: str) -> Dict[str, Any]:
    exe = find_godot(console=False)
    if not exe:
        return {"status": "error", "message": "Godot isn't installed."}
    manifest = studio.read_manifest(path) or {}
    proc = subprocess.Popen([exe, "--path", path])
    return {"status": "success", "pid": proc.pid, "title": manifest.get("window_title", ""),
            "message": f"Started {manifest.get('title', 'the game')} in Godot."}
