"""Write a document's content with a small local model — outline first, then one section at a time.

One giant JSON request ("give me the whole document as JSON") is what made TOM's files look like
templates: a 3B model returns a skeleton with one-line sections, and a broken bracket turned the
whole thing into a placeholder. Here the model only returns a short JSON outline, then writes each
section as plain text (which small models do well), and every section passes a quality check —
no placeholders, enough substance — with one rewrite when it fails.
"""
from __future__ import annotations

import re
from typing import Any, Awaitable, Callable, Dict, List, Optional

from tom_core.documents.spec import DocSpec, outline_hint
from tom_core.llm_json import parse_model_json

Ask = Callable[[str, str], Awaitable[str]]

BANNED = re.compile(
    r"lorem ipsum|\[(?:insert|your|add|company|name|date|enter|placeholder)[^\]]*\]|\bplaceholder\b|\bTBD\b|"
    r"bullet point \d|\bslide title\b|\bsection title\b|generated by tom|as an ai\b|i cannot provide|"
    r"here is (?:the|a|your)\b[^.\n]*:|^sure[,!]", re.I | re.M)

WRITER = (
    "You are an expert professional writer producing a polished {genre} in American English for {audience}. "
    "Write real, specific, substantive content: concrete facts, numbers, examples and clear reasoning, in a "
    "{tone} tone. Never write placeholders such as [Insert ...], 'Lorem ipsum', 'TBD' or 'Your Name', and no "
    "preamble such as 'Here is'. Format: plain paragraphs; lines starting with '- ' for a bullet list; lines like "
    "'| A | B |' for a table (first row is the header); '### ' for a sub-heading; **bold** for key terms. "
    "Do not repeat the section heading or the document title. Never name a specific study, journal, survey, "
    "report or exact statistic unless it appears in the research notes you are given — otherwise describe evidence "
    "and trends in general terms (e.g. 'studies suggest', 'adoption is growing').")


# ── parsing plain text into blocks ──────────────────────────────────────────
def parse_blocks(text: str) -> List[Dict[str, Any]]:
    """Markdown-lite → blocks: heading / paragraph / bullets / numbered / table / callout."""
    blocks: List[Dict[str, Any]] = []
    para: List[str] = []
    code: Optional[List[str]] = None
    # inline links [text](url) → text (url)
    text = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)",
                  lambda m: m.group(1) if m.group(1) in m.group(2) else f"{m.group(1)} ({m.group(2)})", text or "")
    # fences the model wrote mid-paragraph ("... example: ```python x = 5 ```") start on their own line
    text = re.sub(r"```(\w*)\s*", lambda m: f"\n```{m.group(1)}\n", text)

    def flush():
        if para:
            blocks.append({"type": "paragraph", "text": " ".join(para).strip()})
            para.clear()

    for raw in (text or "").replace("\r", "").split("\n"):
        if raw.strip().startswith("```"):
            if code is None:
                flush()
                code = []
            else:
                if any(c.strip() for c in code):
                    blocks.append({"type": "code", "text": "\n".join(code).strip("\n")})
                code = None
            continue
        if code is not None:
            code.append(raw.rstrip())
            continue
        line = raw.strip()
        if not line or set(line) <= set("-=*_ "):
            flush()
            continue
        if line.startswith("|") and line.count("|") >= 2:
            flush()
            cells = [c.strip().strip("*") for c in line.strip("|").split("|")]
            if all(re.fullmatch(r":?-{2,}:?", c) for c in cells if c):
                continue                                         # the |---|---| separator row
            last = blocks[-1] if blocks else None
            if last and last["type"] == "table":
                last["rows"].append(cells)
            else:
                blocks.append({"type": "table", "headers": cells, "rows": []})
            continue
        m = re.match(r"^(#{1,4})\s+(.*)", line)
        if m:
            flush()
            blocks.append({"type": "heading", "text": m.group(2).strip(" *#"), "level": 2})
            continue
        m = re.match(r"^(?:[-*•▪●]|•)\s+(.*)", line)
        if m:
            flush()
            if blocks and blocks[-1]["type"] == "bullets":
                blocks[-1]["items"].append(m.group(1).strip())
            else:
                blocks.append({"type": "bullets", "items": [m.group(1).strip()]})
            continue
        m = re.match(r"^\d{1,2}[.)]\s+(.*)", line)
        if m:
            flush()
            if blocks and blocks[-1]["type"] == "numbered":
                blocks[-1]["items"].append(m.group(1).strip())
            else:
                blocks.append({"type": "numbered", "items": [m.group(1).strip()]})
            continue
        if line.startswith(">"):
            flush()
            blocks.append({"type": "callout", "text": line.lstrip("> ").strip()})
            continue
        para.append(line)
    flush()
    if code:
        blocks.append({"type": "code", "text": "\n".join(code).strip("\n")})
    for b in blocks:                                             # tidy ragged tables
        if b["type"] == "table":
            n = len(b["headers"])
            b["rows"] = [(r + [""] * n)[:n] for r in b["rows"]]
    return [b for b in blocks if not (b["type"] == "table" and not b["rows"])]


def words(blocks: List[Dict[str, Any]]) -> int:
    n = 0
    for b in blocks:
        if "text" in b:
            n += len(b["text"].split())
        for it in b.get("items", []):
            n += len(it.split())
        for row in b.get("rows", []):
            n += sum(len(str(c).split()) for c in row)
    return n


def problems(text: str, min_words: int, allow_fields: bool = False) -> List[str]:
    found = []
    for m in BANNED.finditer(text or ""):
        if allow_fields and m.group(0).startswith("["):
            continue
        found.append(m.group(0).strip()[:40])
    n = len((text or "").split())
    if n < min_words:
        found.append(f"only {n} words (need about {min_words})")
    return found


def _strip_banned(text: str) -> str:
    lines = [ln for ln in (text or "").split("\n") if not re.match(r"^\s*(here is|here's|sure|certainly)\b", ln, re.I)]
    return "\n".join(lines).strip()


def _strip_heading_echo(text: str, heading: str) -> str:
    lines = (text or "").strip().split("\n")
    if lines and re.sub(r"[#*\s:]", "", lines[0]).lower() == re.sub(r"[#*\s:]", "", heading).lower():
        lines = lines[1:]
    return "\n".join(lines).strip()


# ── documents (Word / PDF) ──────────────────────────────────────────────────
async def outline(spec: DocSpec, ask: Ask, research: str = "") -> Dict[str, Any]:
    hint = outline_hint(spec)
    system = ("You plan professional documents. Return ONLY JSON: "
              '{"title": "specific, compelling title", "subtitle": "one-line subtitle", '
              '"sections": [{"heading": "section heading", "purpose": "what this section covers, one line"}]}')
    user = (f"{spec.brief()}\n\nPlan {spec.target_sections} sections. A good structure for this kind of "
            f"document is: {', '.join(hint)}. Adapt the headings to the topic so they are specific, not generic."
            + (f"\n\nResearch notes:\n{research[:1500]}" if research else ""))
    raw = await ask(system, user)
    try:
        try:
            data = parse_model_json(raw)
        except Exception:
            heads = re.findall(r'"heading"\s*:\s*"([^"]{3,90})"', raw or "")
            t = re.search(r'"title"\s*:\s*"([^"]{3,120})"', raw or "")
            s_ = re.search(r'"subtitle"\s*:\s*"([^"]{3,160})"', raw or "")
            data = {"title": t.group(1) if t else "", "subtitle": s_.group(1) if s_ else "",
                    "sections": [{"heading": h} for h in heads]}
        secs = [s for s in (data.get("sections") or []) if isinstance(s, dict) and str(s.get("heading", "")).strip()]
        if len(secs) >= 3 and not BANNED.search(str(data)):
            return {"title": str(data.get("title") or title_case(spec.topic))[:120],
                    "subtitle": str(data.get("subtitle") or "")[:160],
                    "sections": [{"heading": str(s["heading"])[:90], "purpose": str(s.get("purpose", ""))[:200]}
                                 for s in secs[:spec.target_sections + 2]]}
    except Exception:
        pass
    sub = {"report": "An analysis of the current landscape, key findings and recommendations",
           "proposal": "Proposal, plan and expected outcomes", "guide": "A practical step-by-step guide",
           "essay": "", "notes": "Key concepts and quick-revision notes"}.get(spec.genre, "")
    if spec.audience:
        sub = (sub + f" — prepared for {spec.audience}").strip(" —")
    return {"title": title_case(spec.topic), "subtitle": sub,
            "sections": [{"heading": h, "purpose": ""} for h in hint]}


_SMALL = {"a", "an", "and", "as", "at", "but", "by", "for", "in", "of", "on", "or", "the", "to", "vs", "via", "with"}


def title_case(text: str) -> str:
    words = (text or "").split()
    return " ".join(w if (w.isupper() and len(w) > 1) else (w.lower() if i and w.lower() in _SMALL else w[:1].upper() + w[1:])
                    for i, w in enumerate(words))


def _same(a: str, b: str) -> bool:
    wa = set(re.findall(r"[a-z0-9]+", (a or "").lower()))
    wb = set(re.findall(r"[a-z0-9]+", (b or "").lower()))
    return bool(wa) and len(wa & wb) / max(len(wa | wb), 1) >= 0.6


async def write_section(spec: DocSpec, plan: Dict[str, Any], section: Dict[str, Any], ask: Ask,
                        research: str = "") -> Dict[str, Any]:
    allow_fields = spec.genre == "resume"
    system = WRITER.format(genre=spec.genre, audience=spec.audience or "a professional reader", tone=spec.tone)
    if allow_fields:
        system += (" Use only facts given in the request about the person; for any unknown personal detail write "
                   "a short bracketed field like [Company Name] for the user to fill in.")
    others = ", ".join(s["heading"] for s in plan["sections"])
    user = (f"{spec.brief()}\n\nDocument title: {plan['title']}\nAll sections, in order: {others}\n\n"
            f"Write the section \"{section['heading']}\"" + (f" — {section['purpose']}" if section.get("purpose") else "")
            + f". About {spec.words_per_section} words. Use a table or bullet list where it helps the reader."
            + (f"\n\nUse these research notes for facts (cite sources as [1], [2]):\n{research[:2500]}" if research else ""))
    best, best_issues = "", ["empty"]
    for attempt in range(2):
        text = _strip_heading_echo(_strip_banned(await ask(system, user)), section["heading"])
        issues = problems(text, int(spec.words_per_section * 0.45), allow_fields)
        if len(issues) < len(best_issues) or not best:
            best, best_issues = text, issues
        if not issues:
            break
        user += f"\n\nYour previous draft had problems ({'; '.join(issues[:3])}). Rewrite it fully and fix them."
    blocks = parse_blocks(best)
    while blocks and blocks[0]["type"] == "heading" and (_same(blocks[0]["text"], plan["title"])
                                                         or _same(blocks[0]["text"], section["heading"])):
        blocks.pop(0)
    for b in blocks:
        if b["type"] == "table":
            b["headers"] = [c.replace("**", "").strip() for c in b["headers"]]
            b["rows"] = [[str(c).replace("**", "").strip() for c in r] for r in b["rows"]]
        elif b["type"] in ("bullets", "numbered"):
            b["items"] = [re.sub(r"\*\*(?![^*]*\*\*)", "", it) for it in b["items"]]
    return {"heading": section["heading"], "blocks": blocks, "issues": best_issues}


async def write_document(spec: DocSpec, ask: Ask, research: str = "",
                         progress: Optional[Callable[[str], None]] = None) -> Dict[str, Any]:
    if spec.genre == "letter":
        return await write_letter(spec, ask)
    plan = await outline(spec, ask, research)
    sections = []
    for i, sec in enumerate(plan["sections"], 1):
        if progress:
            progress(f"Writing section {i}/{len(plan['sections'])}: {sec['heading']}")
        sections.append(await write_section(spec, plan, sec, ask, research))
    return {"title": plan["title"], "subtitle": plan["subtitle"], "sections": sections,
            "issues": [f"{s['heading']}: {i}" for s in sections for i in s["issues"]]}


async def write_letter(spec: DocSpec, ask: Ask) -> Dict[str, Any]:
    system = (WRITER.format(genre="letter", audience=spec.recipient or "the recipient", tone=spec.tone) +
              " Write ONLY two parts:\nSUBJECT: <a clear subject line>\nBODY:\n<3-5 well-formed paragraphs>\n"
              "No address block, no date, no 'Dear ...' greeting, no closing and no signature — those are added "
              "automatically. Use concrete details from the request (dates, reasons, names).")
    user = spec.brief()
    best, issues = "", ["empty"]
    for _ in range(2):
        text = _strip_banned(await ask(system, user))
        m = re.search(r"SUBJECT:\s*(.+)", text, re.I)
        body = re.split(r"BODY:\s*", text, maxsplit=1, flags=re.I)
        body_text = body[1] if len(body) > 1 else re.sub(r"SUBJECT:.*", "", text, flags=re.I)
        body_text = re.sub(r"^\s*(?:subject|re)\s*:[^\n]*\n", "", body_text.strip(), flags=re.I | re.M)
        body_text = re.sub(r"^\s*(?:january|february|march|april|may|june|july|august|september|october|"
                           r"november|december)\s+\d{1,2},?\s+\d{4}\s*$", "", body_text, flags=re.I | re.M).strip()
        body_text = re.sub(r"^\s*(dear\b[^\n]*|to whom[^\n]*)\n", "", body_text.strip(), flags=re.I)
        body_text = re.split(r"\n\s*(sincerely|regards|best regards|yours (?:sincerely|faithfully|truly)|thank you,?)\s*[,\n]",
                             body_text, flags=re.I)[0].strip()
        found = problems(body_text, 70)
        if not best or len(found) < len(issues):
            best, issues = body_text, found
            subject = m.group(1).strip(" *") if m else letter_subject(spec)
        if not found:
            break
        user += f"\n\nYour previous draft had problems ({'; '.join(found[:3])}). Rewrite it fully."
    return {"title": subject, "subtitle": "", "letter": True, "subject": subject,
            "sections": [{"heading": "", "blocks": parse_blocks(best), "issues": issues}],
            "issues": issues}


def letter_subject(spec: DocSpec) -> str:
    low = spec.request.lower()
    for rx, subj in ((r"sick|fever|ill\b|unwell", "Request for Sick Leave"), (r"\bleave\b", "Leave Request"),
                     (r"resign", "Letter of Resignation"), (r"complain", "Formal Complaint"),
                     (r"recommend", "Letter of Recommendation"), (r"cover letter|job|position", "Application for the Position"),
                     (r"apolog", "Apology"), (r"invit", "Invitation"), (r"permission", "Request for Permission")):
        if re.search(rx, low):
            return subj
    t = re.sub(r"\b(letter|to (?:my|the|our) \w+|for (?:tomorrow|today))\b", " ", spec.topic, flags=re.I)
    return re.sub(r"\s+", " ", t).strip().capitalize() or "Request"


# ── presentations ───────────────────────────────────────────────────────────
SLIDE_KINDS = ("bullets", "cards", "stats", "chart", "timeline", "table", "statement", "two_column")


async def deck_outline(spec: DocSpec, ask: Ask, research: str = "") -> Dict[str, Any]:
    n = spec.slides
    system = ("You plan professional slide decks. Return ONLY JSON: "
              '{"title": "deck title", "subtitle": "one-line subtitle", "slides": [{"title": "slide headline", '
              '"kind": "bullets|cards|stats|chart|timeline|table|statement|two_column"}]}. '
              "Headlines are short (max 8 words) and specific. Mix slide kinds: use 'stats' or 'chart' for numbers, "
              "'timeline' for phases or history, 'cards' for 3-4 parallel ideas, 'table' for comparisons. "
              "Give ONLY the headline and kind for each slide — no slide content, no text, no data.")
    user = (f"{spec.brief()}\n\nPlan exactly {n} content slides (the title slide, agenda and closing slide are "
            "added automatically, so do not include them)." + (f"\n\nResearch notes:\n{research[:1500]}" if research else ""))
    raw = await ask(system, user)
    try:
        try:
            data = parse_model_json(raw)
        except Exception:
            data = _salvage_outline(raw)                     # truncated / broken JSON: keep the headlines
        slides = [s for s in (data.get("slides") or []) if isinstance(s, dict) and str(s.get("title", "")).strip()]
        if not research:
            slides = [s for s in slides if not re.search(r"\b(references|sources|bibliography)\b", s["title"], re.I)]
        slides = [s for s in slides if not re.search(r"\b(agenda|thank you|questions|title slide)\b", s["title"], re.I)]
        seen, uniq = [_words(str(data.get("title") or spec.topic))], []
        for s in slides:
            w = _words(s["title"])
            if w and all(len(w & o) / max(len(w | o), 1) < 0.7 for o in seen):
                seen.append(w)
                uniq.append(s)
        slides = uniq
        if len(slides) >= max(3, n // 2):
            out = [{"title": str(s["title"])[:70],
                    "kind": "statement" if s.get("kind") == "quote" else (s.get("kind") if s.get("kind") in SLIDE_KINDS else "bullets")}
                   for s in slides[:n]]
            while len(out) < n:
                out.append({"title": f"{spec.topic.title()}: Key Point {len(out) + 1}", "kind": "bullets"})
            return {"title": str(data.get("title") or spec.topic.title())[:90],
                    "subtitle": str(data.get("subtitle") or "")[:140], "slides": out}
    except Exception:
        pass
    base = ["Overview", "Why It Matters", "Key Facts in Numbers", "How It Works", "Main Benefits", "Challenges",
            "Comparison of Options", "Roadmap", "Best Practices", "Case Example", "Future Outlook", "Key Takeaways"]
    kinds = ["bullets", "cards", "stats", "bullets", "cards", "bullets", "table", "timeline", "bullets", "statement",
             "chart", "cards"]
    return {"title": spec.topic.title(), "subtitle": f"Presented by {spec.sender}" if spec.sender else "",
            "slides": [{"title": base[i % len(base)], "kind": kinds[i % len(kinds)]} for i in range(n)]}


def _words(text: str) -> set:
    return {w for w in re.findall(r"[a-z0-9]+", (text or "").lower()) if w not in ("the", "of", "and", "in", "for", "a", "an", "to", "ev")}


def _salvage_outline(raw: str) -> Dict[str, Any]:
    titles = re.findall(r'"title"\s*:\s*"([^"]{3,90})"', raw or "")
    kinds = re.findall(r'"kind"\s*:\s*"(\w+)"', raw or "")
    first = titles[0] if titles else ""
    slides = [{"title": t, "kind": kinds[i - 1] if 0 < i <= len(kinds) else "bullets"} for i, t in enumerate(titles) if i]
    return {"title": first, "slides": slides}


_SLIDE_FORMAT = (
    "For EACH slide write exactly this block:\n"
    "=== SLIDE: <headline>\n"
    "- <point, max 14 words, specific and informative>\n"
    "- <3 to 5 points in total>\n"
    "DATA: <only for stats/chart slides: 3-6 pairs like  2024 = 120; 2030 = 450 (unit: $ billion)>\n"
    "NOTES: <2-3 sentences the presenter says>\n"
    "For 'cards' slides write 3-4 points as 'Short Heading: one full sentence of 12-20 words'. For 'timeline' "
    "slides start EVERY point with a year or phase, e.g. '2024: ...' or 'Phase 1: ...'. For 'statement' slides the "
    "first point is one strong key message (one sentence) and the others support it. For 'table' slides write rows "
    "as 'Option | attribute | attribute' with the first line being the header. Never invent quotations.")


def parse_slides(text: str) -> List[Dict[str, Any]]:
    slides = []
    marker = re.compile(r"^\s*(?:={2,}\s*)?[#*]*\s*SLIDE\b(?:\s*\d+)?\s*[:.\-–]?\s*", re.M | re.I)
    for chunk in marker.split(text or "")[1:]:
        lines = chunk.strip().split("\n")
        title = re.sub(r"^\s*(?:title|headline)\s*:\s*", "", lines[0].strip(" =*#"), flags=re.I).strip(" =*#")
        bullets, notes, data = [], "", []
        for ln in lines[1:]:
            s = ln.strip()
            if re.match(r"^NOTES?:", s, re.I):
                notes = s.split(":", 1)[1].strip()
            elif re.match(r"^DATA:", s, re.I):
                for pair in re.split(r";|,(?=\s*[A-Za-z])", s.split(":", 1)[1]):
                    m = re.match(r"\s*(.+?)\s*[=:]\s*\$?(-?[\d,.]+)\s*(%|[kKmMbB]n?|million|billion)?", pair)
                    if m:
                        try:
                            unit_m = re.search(r"\(unit:\s*([^)]+)\)", s, re.I)
                            data.append((re.sub(r"^label\s*", "", m.group(1).strip(" *"), flags=re.I),
                                         float(m.group(2).replace(",", "")),
                                         m.group(3) or (unit_m.group(1).strip() if unit_m else "")))
                        except ValueError:
                            pass
            elif re.match(r"^(?:[-*•]|\d+[.)])\s+", s):
                b = re.sub(r"^(?:[-*•]|\d+[.)])\s+", "", s).strip()
                b = re.sub(r"^(?:label|point|bullet)\s*[=:]\s*:?\s*", "", b, flags=re.I)
                bullets.append(b)
            elif notes and s:
                notes += " " + s
        if title:
            slides.append({"title": title[:80], "bullets": [b for b in bullets if b][:6], "notes": notes[:600],
                           "data": data[:6]})
    return slides


def _thin(slide: Dict[str, Any]) -> bool:
    b = slide.get("bullets") or []
    if slide.get("kind") == "statement":
        return not b or len(b[0].split()) < 6
    if len(b) < 2:
        return True
    avg = sum(len(x.split()) for x in b) / len(b)
    if slide.get("kind") == "cards":
        return any(len((x.split(":", 1)[1] if ":" in x[:50] else x).split()) < 5 for x in b)
    return avg < 5


async def write_deck(spec: DocSpec, ask: Ask, research: str = "",
                     progress: Optional[Callable[[str], None]] = None) -> Dict[str, Any]:
    plan = await deck_outline(spec, ask, research)
    system = (f"You write slide content for a professional {spec.tone} presentation in American English for "
              f"{spec.audience or 'a professional audience'}. Content is concrete and specific — real facts, "
              "numbers and examples, never placeholders, never 'Bullet 1'. Do not name specific studies or "
              "reports unless they appear in the research notes. Every point must be specifically about its slide's "
              "headline — if the headline names a country, company or market, the points must be about exactly that. "
              + _SLIDE_FORMAT)
    written: List[Dict[str, Any]] = []
    batch = 2
    for i in range(0, len(plan["slides"]), batch):
        group = plan["slides"][i:i + batch]
        if progress:
            progress(f"Writing slides {i + 1}-{i + len(group)} of {len(plan['slides'])}")
        listing = "\n".join(f"- {s['title']} (kind: {s['kind']})" for s in group)
        user = (f"{spec.brief()}\n\nDeck title: {plan['title']}\nWrite these slides:\n{listing}"
                + (f"\n\nResearch notes (use for facts and numbers):\n{research[:2000]}" if research else ""))
        got = parse_slides(await ask(system, user))
        if len(got) < len(group):                                    # one retry for a short batch
            got = parse_slides(await ask(system, user + "\n\nWrite ALL of the slides listed, each with '=== SLIDE:'."))
        for j, s in enumerate(group):
            g = got[j] if j < len(got) else {"title": s["title"], "bullets": [], "notes": "", "data": []}
            g["title"] = s["title"]                                  # the planned headline stays
            g["kind"] = s["kind"]
            written.append(g)
    for k, s in enumerate(written):                                  # one focused retry per thin slide
        if _thin(s):
            got = parse_slides(await ask(system, f"{spec.brief()}\n\nDeck title: {plan['title']}\nWrite this one "
                                                 f"slide:\n- {s['title']} (kind: {s['kind']})"))
            if got and not _thin({**got[0], "kind": s["kind"]}):
                written[k] = {**got[0], "title": s["title"], "kind": s["kind"]}
    issues = [f"slide '{s['title']}': thin content" for s in written if _thin(s)]
    issues += [f"slide '{s['title']}': {m.group(0)}" for s in written for m in [BANNED.search(" ".join(s["bullets"]))] if m]
    return {"title": plan["title"], "subtitle": plan["subtitle"], "slides": written, "issues": issues,
            "data_from_research": bool(research)}


# ── workbooks ───────────────────────────────────────────────────────────────
async def write_workbook(spec: DocSpec, ask: Ask, research: str = "") -> Dict[str, Any]:
    system = ("You design professional Excel workbooks. Return ONLY JSON: "
              '{"title": "workbook title", "sheets": [{"name": "short sheet name", "description": "one line", '
              '"columns": [{"name": "Column", "type": "text|number|currency|percent|date"}], '
              '"rows": [["value", 123]], "chart": {"type": "bar|line|pie|none", "label_column": "Column", '
              '"value_columns": ["Column"]}}]}. '
              "Give 10-20 realistic rows per sheet with real numbers (not strings) in number columns, percent as "
              "fractions (0.25), dates as YYYY-MM-DD. Use one sheet for each part of the request (for example "
              "separate Income and Expenses sheets), 1-4 sheets. No totals rows — they are added automatically.")
    user = spec.brief() + (f"\n\nResearch notes:\n{research[:2000]}" if research else "")
    last_error = None
    for attempt in range(3):
        try:
            data = parse_model_json(await ask(system, user if attempt == 0 else user + "\n\nReturn valid JSON only."))
            if isinstance(data, list):
                data = {"sheets": data}
            if "sheets" not in data and (data.get("columns") or data.get("headers")):
                data = {"title": data.get("title"), "sheets": [data]}         # one sheet at the top level
            for s in data.get("sheets", []):
                if isinstance(s, dict):
                    s.setdefault("columns", s.get("headers") or [])
                    s.setdefault("rows", s.get("data") or [])
            sheets = [s for s in data.get("sheets", []) if isinstance(s, dict) and s.get("columns") and s.get("rows")]
            if sheets:
                return {"title": str(data.get("title") or spec.topic.title()), "sheets": sheets,
                        "data_from_user": bool(re.search(r"\d", spec.request)) and len(spec.request) > 200,
                        "data_from_research": bool(research)}
        except Exception as exc:
            last_error = exc
    raise ValueError(f"The model did not return usable spreadsheet data ({last_error or 'no sheets'}).")
